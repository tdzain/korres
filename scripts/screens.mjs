// Gera screenshots do fluxo (carrinho, checkout, confirmação) para revisão visual. Uso: node scripts/screens.mjs <base> <outdir> <w> <h>
import { chromium } from '@playwright/test'
const [base = 'http://localhost:8788', out = 'docs/reference', w = '1440', h = '900'] = process.argv.slice(2)
const tag = Number(w) < 700 ? 'm' : 'd'
const b = await chromium.launch()
const ctx = await b.newContext({ viewport: { width: Number(w), height: Number(h) }, locale: 'pt-BR', isMobile: tag === 'm', hasTouch: tag === 'm' })
await ctx.addInitScript(() => localStorage.setItem('kr_prefs', JSON.stringify({ state: { cookies: 'all', newsletter: 'dismissed', recentSearches: [] }, version: 0 })))
const p = await ctx.newPage()
await p.route('**/api/geo', (r) => r.fulfill({ json: { city: 'Curitiba', uf: 'PR', source: 'edge' } }))
await p.route('**/api/cep/80010000', (r) => r.fulfill({ json: { cep: '80010-000', street: 'Rua José Loureiro', neighborhood: 'Centro', city: 'Curitiba', uf: 'PR' } }))
await p.goto(`${base}/produto/black-pine-sculpt-lift-serum/?demo=1`)
await p.waitForTimeout(2500)
await p.screenshot({ path: `${out}/shot-pdp-${tag}.png` })
await p.getByTestId('add-to-bag').click()
await p.waitForTimeout(1800)
await p.screenshot({ path: `${out}/shot-cart-${tag}.png` })
await p.getByRole('link', { name: /Ir para o checkout/i }).click()
await p.waitForTimeout(2500)
await p.screenshot({ path: `${out}/shot-checkout-${tag}.png`, fullPage: true })
await p.getByLabel('E-mail').fill('maria@example.com')
await p.getByLabel('Celular com DDD').fill('41999990000')
await p.getByLabel('CEP').fill('80010000'); await p.waitForTimeout(900)
await p.getByLabel('Nome', { exact: true }).fill('Maria'); await p.getByLabel('Sobrenome').fill('Teste'); await p.getByLabel('CPF').fill('52998224725')
await p.getByLabel('Número', { exact: true }).fill('100')
await p.getByText('Cartão de crédito', { exact: true }).click()
await p.getByLabel('CVV').focus()
await p.waitForTimeout(900)
await p.screenshot({ path: `${out}/shot-checkout-card-${tag}.png`, fullPage: true })
await p.getByText('Aprovação imediata').click()
await p.locator('[data-testid="place-order"]:visible').click()
await p.waitForURL(/pedido/)
await p.waitForTimeout(2500)
await p.screenshot({ path: `${out}/shot-order-${tag}.png`, fullPage: true })
await b.close()
