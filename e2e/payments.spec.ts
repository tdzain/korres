import { expect, test } from '@playwright/test'
import { goToCheckoutWithItem, mockExternal, watchConsole } from './helpers'

const finish = (page: import('@playwright/test').Page) => page.locator('[data-testid="place-order"]:visible').click()

test.describe('checkout de demonstração', () => {
  test('preencher com dados aleatórios e finalizar mostra confirmação e QR Code do Pix', async ({ page }) => {
    const errors = watchConsole(page)
    await mockExternal(page)
    await goToCheckoutWithItem(page)
    await page.getByTestId('fill-random').click()
    await expect(page.getByLabel('Rua')).not.toHaveValue('')
    await expect(page.getByLabel('CPF')).toHaveValue(/^\d{3}\.\d{3}\.\d{3}-\d{2}$/)
    await finish(page)
    await expect(page).toHaveURL(/\/pedido\/KR[A-Z0-9]{8}\/$/)
    await expect(page.getByTestId('pix-qr')).toBeVisible()
    await expect(page.getByTestId('copy-value')).toContainText('br.gov.bcb.pix')
    expect(errors, errors.join('\n')).toEqual([])
  })

  test('"Preencher e finalizar" faz tudo em um clique', async ({ page }) => {
    await mockExternal(page)
    await goToCheckoutWithItem(page)
    await page.getByTestId('fill-and-submit').click()
    await expect(page).toHaveURL(/\/pedido\/KR[A-Z0-9]{8}\/$/, { timeout: 20_000 })
    await expect(page.getByTestId('pix-qr')).toBeVisible()
  })

  test('venda híbrida Pix + cartão: QR só da parte do Pix, cartão aprovado na hora', async ({ page }) => {
    await mockExternal(page)
    await goToCheckoutWithItem(page)
    await page.getByTestId('fill-random').click()
    await page.getByText('Pagar em duas formas', { exact: true }).click()
    const split = page.getByTestId('split-panel')
    await expect(split).toBeVisible()
    await split.getByRole('button', { name: '50%' }).click()
    const breakdown = split.getByTestId('split-breakdown')
    await expect(breakdown).toContainText('Pix')
    await expect(breakdown).toContainText('Cartão')
    await finish(page)
    await expect(page).toHaveURL(/\/pedido\/KR[A-Z0-9]{8}\/$/)
    const parts = page.getByTestId('parts-panel')
    await expect(parts).toContainText('Pix')
    await expect(parts).toContainText('Cartão')
    await expect(parts).toContainText('Aguardando')
    await expect(parts).toContainText('Aprovado')
    await expect(page.getByTestId('pix-qr')).toBeVisible()
    // O valor do QR é só a parte do Pix (menor que o total do pedido).
    const pix = Number((await page.getByTestId('pix-amount').textContent())!.replace(/[^\d,]/g, '').replace(',', '.'))
    const total = Number((await page.getByTestId('confirm-total').textContent())!.replace(/[^\d,]/g, '').replace(',', '.'))
    expect(pix).toBeGreaterThan(0)
    expect(pix).toBeLessThan(total)
  })

  test('venda híbrida em dois cartões: sem Pix, tudo aprovado', async ({ page }) => {
    await mockExternal(page)
    await goToCheckoutWithItem(page)
    await page.getByTestId('fill-random').click()
    await page.getByText('Pagar em duas formas', { exact: true }).click()
    await page.getByTestId('split-mode-card_card').click()
    const split = page.getByTestId('split-panel')
    await expect(split.getByText('Cartão 1').first()).toBeVisible()
    await expect(split.getByText('Cartão 2').first()).toBeVisible()
    await split.getByRole('button', { name: '25%' }).click()
    await finish(page)
    await expect(page).toHaveURL(/\/pedido\/KR[A-Z0-9]{8}\/$/)
    const parts = page.getByTestId('parts-panel')
    await expect(parts).toContainText('Cartão 1')
    await expect(parts).toContainText('Cartão 2')
    await expect(parts.getByText('Aprovado')).toHaveCount(2)
    await expect(page.getByTestId('pix-qr')).toHaveCount(0)
  })

  test('mesmo cartão duas vezes é barrado', async ({ page }) => {
    await mockExternal(page)
    await goToCheckoutWithItem(page)
    await page.getByTestId('fill-random').click()
    await page.getByText('Pagar em duas formas', { exact: true }).click()
    await page.getByTestId('split-mode-card_card').click()
    const split = page.getByTestId('split-panel')
    const numbers = split.getByLabel('Número do cartão')
    await numbers.nth(1).fill(await numbers.nth(0).inputValue())
    await finish(page)
    await expect(page.getByText('Use um segundo cartão diferente do primeiro')).toBeVisible()
  })
})

test.describe('concierge e assinatura', () => {
  test('botão flutuante do WhatsApp abre o concierge e leva ao wa.me com contexto', async ({ page, context }) => {
    await mockExternal(page)
    await context.route('https://wa.me/**', (r) => r.fulfill({ status: 200, contentType: 'text/html', body: '<title>wa</title>ok' }))
    await page.goto('/produto/smart-yoghurt-probiotic-super-serum/')
    await page.getByTestId('wa-fab').click()
    const dlg = page.getByRole('dialog', { name: 'Concierge KORRES no WhatsApp' })
    await expect(dlg).toContainText('Concierge KORRES')
    const [popup] = await Promise.all([context.waitForEvent('page'), dlg.getByTestId('wa-intent').first().click()])
    const url = decodeURIComponent(popup.url())
    expect(url).toContain('wa.me')
    expect(url).toContain('concierge KORRES')
    expect(url).toContain('Smart Yoghurt Probiotic Super Serum')
  })

  test('home sem rolagem horizontal e com o botão do WhatsApp clicável', async ({ page }) => {
    await mockExternal(page)
    await page.goto('/')
    const fab = page.getByTestId('wa-fab')
    await fab.waitFor()
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)
    expect(overflow).toBeLessThanOrEqual(0)
    await fab.click({ timeout: 5000 })
    await expect(page.getByRole('dialog', { name: 'Concierge KORRES no WhatsApp' })).toBeVisible()
  })

  test('assinatura tdzain com link para tdzain.com', async ({ page }) => {
    await mockExternal(page)
    await page.goto('/')
    const sign = page.getByTestId('made-by').getByRole('link')
    await expect(sign).toHaveAttribute('href', 'https://tdzain.com')
    await expect(sign).toContainText('tdzain')
    await expect(sign).toContainText('Crafting. Building. Tailor-made.')
    await expect(sign).toHaveAttribute('target', '_blank')
  })
})
